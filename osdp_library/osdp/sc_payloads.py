from dataclasses import dataclass
from typing import Any, ClassVar

from .constants import CommandTags, ResponseTags, SecurityConstants
from .exceptions import PayloadValidationError
from .payload import OsdpBasePayload


@dataclass
class OsdpKeysetPayload(OsdpBasePayload):
    """
    osdp_KEYSET payload for secure channel base key management.

    Byte structure (3 + key_length bytes):
    [0] key_type - Key type identifier (0x01 for SCBK)
    [1] key_length - Length of key data in bytes
    [2...2+key_length-1] key_data - Key data bytes
    """

    key_type: int
    """
    Key type identifier (0x01 for SCBK)
    """

    key_length: int
    """
    Length of the key data in bytes
    """

    key_data: bytes
    """
    Key data bytes
    """

    MIN_DATA_LEN: int = 3

    def __post_init__(self):
        """Validate field values after initialization."""
        if self.key_type < 0 or self.key_type > 255:
            raise PayloadValidationError(f"Invalid key_type: {self.key_type}")
        if self.key_length < 0 or self.key_length > 255:
            raise PayloadValidationError(f"Invalid key_length: {self.key_length}")
        if len(self.key_data) != self.key_length:
            raise PayloadValidationError(f"key_length ({self.key_length}) does not match key_data length ({len(self.key_data)})")
        if self.key_type == SecurityConstants.SCBK and self.key_length != 16:
            raise PayloadValidationError(f"SCBK key must be 16 bytes, got {self.key_length}")

    def to_bytes(self) -> bytes:
        data = bytearray([self.key_type, self.key_length])
        data.extend(self.key_data)
        return bytes(data)

    @classmethod
    def from_bytearray(cls, ba: bytearray):
        if len(ba) < OsdpKeysetPayload.MIN_DATA_LEN:
            raise PayloadValidationError("osdp_KEYSET payload too short")

        key_type = ba[0]
        key_length = ba[1]

        if len(ba) != OsdpKeysetPayload.MIN_DATA_LEN - 1 + key_length:
            raise PayloadValidationError("osdp_KEYSET payload length mismatch")

        return OsdpKeysetPayload(
            tag=CommandTags.KEYSET,
            key_type=key_type,
            key_length=key_length,
            key_data=bytes(ba[2 : 2 + key_length]),
        )

    def _get_format_fields(self, format_short: bool = False) -> dict[str, Any]:
        """
        Define format fields for KEYSET payload.

        Note: Does not expose key_data for security reasons.

        :param format_short: If True, return short format fields; if False, return long format fields
        :return: Dict mapping field_name -> config dict
        """
        fields = {
            "key_type": {"name": "Key Type", "transform": "hex", "width": 2},
            "key_length": {"name": "Key Length"},
        }
        return fields


@dataclass
class OsdpChlngPayload(OsdpBasePayload):
    """
    osdp_CHLNG payload for secure channel challenge initiation.

    Byte structure (8 bytes):
    [0...7] rnd - 8-byte random number (RNDA) generated by the controller
    """

