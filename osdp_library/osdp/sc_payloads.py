@dataclass
class OsdpCcryptPayload(OsdpBasePayload):
    """
    osdp_CCRYPT payload for client cryptogram response in secure channel.

    Byte structure (32 bytes):
    [0...7] client_id - 8-byte Client's Unique Identifier (cUID)
    [8...15] random_number - 8-byte PD's random number generated (RND.B)
    [16...31] client_cryptogram - 16-byte client cryptogram for authentication
    """

    client_id: bytes
    """
    8-byte Client's Unique Identifier (cUID)
    """

    random_number: bytes
    """
    8-byte PD's random number generated (RND.B)
    """

    client_cryptogram: bytes
    """
    16-byte client cryptogram for authentication
    """

    DATA_LEN: int = 32
    CLIENT_ID_LEN: int = 8
    RANDOM_NUMBER_LEN: int = 8
    CRYPTOGRAM_LEN: int = 16

    TITLE: ClassVar[str] = "CCRYPT Response"
    """
    Title for this payload type.
    """

    def __post_init__(self):
        """Validate field values after initialization."""
        if len(self.client_id) != self.CLIENT_ID_LEN:
            raise PayloadValidationError(f"client_id must be {self.CLIENT_ID_LEN} bytes, got {len(self.client_id)}")
        if len(self.random_number) != self.RANDOM_NUMBER_LEN:
            raise PayloadValidationError(f"random_number must be {self.RANDOM_NUMBER_LEN} bytes, got {len(self.random_number)}")
        if len(self.client_cryptogram) != self.CRYPTOGRAM_LEN:
            raise PayloadValidationError(f"client_cryptogram must be {self.CRYPTOGRAM_LEN} bytes, got {len(self.client_cryptogram)}")

    def to_bytes(self) -> bytes:
        data = bytearray(self.client_id)
        data.extend(self.random_number)
        data.extend(self.client_cryptogram)
        return bytes(data)

    @classmethod
    def from_bytearray(cls, ba: bytearray):
        if len(ba) != OsdpCcryptPayload.DATA_LEN:
            raise PayloadValidationError("osdp_CCRYPT payload bad length")

        return OsdpCcryptPayload(
            tag=ResponseTags.CCRYPT,
            client_id=bytes(ba[0:8]),
            random_number=bytes(ba[8:16]),
            client_cryptogram=bytes(ba[16:32]),
        )

    def _get_format_fields(self, format_short: bool = False) -> dict[str, Any]:
        fields = {
            "_status": {"name": "Status", "compute": lambda p: "Continuing secure channel"},
        }
        if not format_short:
            fields = {
                **fields,
                "tag": {"name": "Message ID", "transform": "hex", "width": 2},
                "_status": {"name": "Status", "compute": lambda p: "Continuing secure channel establishment"},
            }
        return fields


